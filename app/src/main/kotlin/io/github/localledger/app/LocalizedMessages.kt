private val exactMessages = messageResources.filterNot { it.first.contains("%1\$s") }.toMap()
private val messagePatterns = messageResources.filter { it.first.contains("%1\$s") }.map { (text, id) ->
    val parts = Regex("%[0-9]+\\\$s").split(text)
    Regex(parts.joinToString("(.*?)") { Regex.escape(it) }, RegexOption.DOT_MATCHES_ALL) to id
}
internal fun localizedMessage(value: String): String {
    exactMessages[value]?.let { return appString(it) }
    messagePatterns.forEach { (pattern, id) -> pattern.matchEntire(value)?.let { return appString(id, *it.groupValues.drop(1).toTypedArray()) } }
    return value
}
