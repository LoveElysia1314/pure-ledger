"""Regenerate the checked-in Compose vectors from the pinned, local Lucide subset.

No network access or Android SDK required. SVG paths retain upstream ISC/MIT notices.
"""
from pathlib import Path
import hashlib
import json
import math
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "design/icons/lucide"
OUTPUT = ROOT / "app/src/main/kotlin/io/github/localledger/app/ui/CategoryGlyphs.kt"


def number(value):
    n = float(value)
    assert math.isfinite(n)
    return f"{n:g}"


def path(element):
    kind = element.tag.rsplit("}", 1)[-1]
    assert not element.get("transform"), "Transforms must be explicitly converted."
    assert element.get("fill", "none") == "none", "The subset uses outline paths."
    if kind == "path":
        return element.attrib["d"]
    n = lambda key, default="0": number(element.get(key, default))
    if kind == "line":
        return f"M{n('x1')},{n('y1')}L{n('x2')},{n('y2')}"
    if kind in {"polyline", "polygon"}:
        values = re.split(r"[\s,]+", element.attrib["points"].strip())
        assert len(values) >= 4 and len(values) % 2 == 0
        return "M" + " L".join(f"{number(values[i])},{number(values[i+1])}" for i in range(0, len(values), 2)) + ("Z" if kind == "polygon" else "")
    if kind in {"circle", "ellipse"}:
        x, y = float(n("cx")), float(n("cy"))
        rx = float(n("r" if kind == "circle" else "rx"))
        ry = rx if kind == "circle" else float(n("ry"))
        return f"M{x-rx:g},{y:g}a{rx:g},{ry:g} 0 1,0 {2*rx:g},0a{rx:g},{ry:g} 0 1,0 {-2*rx:g},0Z"
    if kind == "rect":
        x, y, w, h = (float(n(k)) for k in ["x", "y", "width", "height"])
        rx = min(float(n("rx", element.get("ry", "0"))), w / 2)
        ry = min(float(n("ry", element.get("rx", "0"))), h / 2)
        return (f"M{x+rx:g},{y:g}H{x+w-rx:g}Q{x+w:g},{y:g} {x+w:g},{y+ry:g}V{y+h-ry:g}"
                f"Q{x+w:g},{y+h:g} {x+w-rx:g},{y+h:g}H{x+rx:g}Q{x:g},{y+h:g} {x:g},{y+h-ry:g}V{y+ry:g}Q{x:g},{y:g} {x+rx:g},{y:g}Z")
    raise ValueError(f"Unsupported SVG element: {kind}")


def main():
    manifest = json.loads((ASSETS / "manifest.json").read_text(encoding="utf-8"))
    assert hashlib.sha256((ASSETS / "LICENSE").read_bytes()).hexdigest() == manifest["license"]["sha256"]
    keys = set(re.findall(r'"([a-z]+)" to ', (ROOT / "core/src/main/kotlin/io/github/localledger/core/CategoryIcons.kt").read_text(encoding="utf-8")))
    assert keys == manifest["icons"].keys(), "Every persisted icon key needs an explicit source mapping."
    definitions = {}
    for key, source in manifest["icons"].items():
        data = (ASSETS / source["file"]).read_bytes()
        assert hashlib.sha256(data).hexdigest() == source["sha256"], source["file"]
        svg = ET.fromstring(data)
        assert svg.attrib["viewBox"] == "0 0 24 24" and svg.get("stroke-width") == "2"
        definitions[key] = [path(node) for node in svg]
        assert definitions[key]
    assert len({tuple(paths) for paths in definitions.values()}) == len(definitions), "Semantic keys should have distinct artwork."
    entries = ",\n".join(f'        {json.dumps(key)} to listOf({", ".join(json.dumps(p) for p in paths)})' for key, paths in definitions.items())
    output = '''package io.github.localledger.app.ui

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

// Generated by scripts/generate_category_icons.py from pinned Lucide SVGs.
// ISC and inherited MIT notices: design/icons/lucide/LICENSE and assets/licenses/Lucide.txt.
internal object CategoryGlyphs {
    private val paths = mapOf(
ENTRIES
    )
    val keys get() = paths.keys
    private val images = paths.mapValues { (key, shapes) -> lazy {
        ImageVector.Builder("Category-$key", 24.dp, 24.dp, 24f, 24f).apply {
            shapes.forEach { shape -> addPath(PathParser().parsePathString(shape).toNodes(),
                stroke = SolidColor(Color.Black), strokeLineWidth = 2f,
                strokeLineCap = StrokeCap.Round, strokeLineJoin = StrokeJoin.Round) }
        }.build()
    } }
    operator fun get(key: String): ImageVector = images.getValue(key.takeIf(images::containsKey) ?: "grid").value
}
'''.replace("ENTRIES", entries)
    OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print(f"Generated {len(definitions)} distinct icons from {manifest['commit']}.")


if __name__ == "__main__":
    main()
